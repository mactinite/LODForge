//! Which LOD levels each reference of a `.statics.bin` has a record in: counts per level set, and
//! the models of references present in a farther level but missing from a nearer one.
//! `cargo run --release -p lodforge-instances --example statics_levels -- <file> [rows] [model substring]`
use std::collections::{BTreeMap, BTreeSet, HashMap};

fn main() {
    let a: Vec<String> = std::env::args().collect();
    let f = lodforge_instances::statics::StaticsFile::from_bytes(&std::fs::read(&a[1]).unwrap()).unwrap();
    let rows: usize = a.get(2).and_then(|s| s.parse().ok()).unwrap_or(40);
    let filt = a.get(3).map(|s| s.to_ascii_lowercase());
    let levels: Vec<u8> = f.blocks.keys().map(|k| k.0).collect::<BTreeSet<_>>().into_iter().collect();
    // Reference -> level -> models.
    let mut refs: HashMap<(u16, u32), BTreeMap<u8, BTreeSet<&str>>> = HashMap::new();
    for (&(level, _, _), recs) in &f.blocks {
        for r in recs {
            if r.plugin == lodforge_instances::statics::NO_PLUGIN {
                continue;
            }
            refs.entry((r.plugin, r.form)).or_default().entry(level).or_default().insert(f.meshes[r.mesh as usize].model.as_str());
        }
    }
    let mut sets: BTreeMap<Vec<u8>, usize> = BTreeMap::new();
    // (level set, models per level) -> references.
    let mut gaps: BTreeMap<(Vec<u8>, String), usize> = BTreeMap::new();
    for by in refs.values() {
        let set: Vec<u8> = by.keys().copied().collect();
        *sets.entry(set.clone()).or_default() += 1;
        let first = levels.iter().position(|l| by.contains_key(l)).unwrap();
        let last = levels.iter().rposition(|l| by.contains_key(l)).unwrap();
        let gap = first > 0 || levels[first..=last].iter().any(|l| !by.contains_key(l));
        if !gap {
            continue;
        }
        let text: Vec<String> = by.iter().map(|(l, m)| format!("LOD{l}: {}", m.iter().copied().collect::<Vec<_>>().join(" + "))).collect();
        let text = text.join(" | ");
        if filt.as_ref().is_some_and(|q| !text.to_ascii_lowercase().contains(q.as_str())) {
            continue;
        }
        *gaps.entry((set, text)).or_default() += 1;
    }
    // Source of the model per level, per reference.
    let mut mix: BTreeMap<String, (usize, String)> = BTreeMap::new();
    for by in refs.values() {
        let key: Vec<String> = by.iter().map(|(l, m)| format!("LOD{l} {}", m.iter().map(|m| source(m)).collect::<BTreeSet<_>>().into_iter().collect::<Vec<_>>().join("+"))).collect();
        let e = mix.entry(key.join(", ")).or_insert((0, String::new()));
        e.0 += 1;
        if e.1.is_empty() {
            e.1 = by.iter().map(|(l, m)| format!("LOD{l}: {}", m.iter().copied().collect::<Vec<_>>().join(" + "))).collect::<Vec<_>>().join(" | ");
        }
    }
    println!("model source per level (references, one example):");
    let mut mix: Vec<_> = mix.into_iter().collect();
    mix.sort_by(|a, b| b.1.0.cmp(&a.1.0));
    for (k, (n, ex)) in &mix {
        println!("{n:>8}  {k}\n            {ex}");
    }
    // Installed (not generated) models by references, nearest level's model.
    let mut installed: BTreeMap<&str, usize> = BTreeMap::new();
    for by in refs.values() {
        for m in by.values().next().unwrap() {
            if source(m) == "installed" {
                *installed.entry(m).or_default() += 1;
            }
        }
    }
    let mut installed: Vec<_> = installed.into_iter().collect();
    installed.sort_by(|a, b| b.1.cmp(&a.1));
    println!("\ninstalled LOD models in use: {} models, {} references", installed.len(), installed.iter().map(|i| i.1).sum::<usize>());
    for (m, n) in installed.iter().take(rows) {
        println!("{n:>6}  {m}");
    }
    println!("\nlevels {levels:?}, {} references", refs.len());
    for (set, n) in &sets {
        println!("{n:>8}  in {set:?}");
    }
    let mut gaps: Vec<_> = gaps.into_iter().collect();
    gaps.sort_by(|a, b| b.1.cmp(&a.1));
    println!("\nreferences missing from a nearer level than one they are in: {} ({} model sets)", gaps.iter().map(|g| g.1).sum::<usize>(), gaps.len());
    for ((set, text), n) in gaps.iter().take(rows) {
        println!("{n:>6}  {set:?}  {text}");
    }
}

/// Where a record's model comes from: generated by LODForge, or installed.
fn source(model: &str) -> &'static str {
    let m = model.to_ascii_lowercase();
    if m.contains(r"\lodforge\baked\") {
        "baked"
    } else if m.contains(r"\lodforge\far\") {
        "far"
    } else if m.contains(r"\lodforge\") {
        "generated"
    } else if m.contains("_lod") {
        "installed"
    } else {
        "full"
    }
}
